#!/bin/sh
set -eu

unformatted=$(gofmt -l cmd services/auth_app/service/service.go services/auth_app/service/service_test.go services/auth_app/delivery/http services/game_app tools)
if [ -n "$unformatted" ]; then
  printf 'Go files need formatting:\n%s\n' "$unformatted"
  exit 1
fi
go test -race -count=1 ./...
go vet ./...
CGO_ENABLED=0 GOOS=linux GOARCH=amd64 go build ./cmd/...
CGO_ENABLED=0 GOOS=linux GOARCH=arm64 go build ./cmd/...
